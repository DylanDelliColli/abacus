//! Validated domain identifiers.
//!
//! Identifiers are inputs: core never generates one (CONTEXT I13; core
//! contract invariant 9). Constructors validate shape and return a
//! normalized error category the caller can act on. The external bead
//! form is `ABACUS-<suffix>`; the lowercase provider form never crosses
//! the work facade (ADR-0001 §3), so core knows only the external form.

use core::fmt;

/// Distinct identifier-validation failures (core contract: normalized
/// error categories).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum IdError {
    Empty,
    TooLong,
    MissingPrefix,
    InvalidCharacter,
    InvalidStructure,
}

const MAX_ID_LEN: usize = 64;

/// External bead identifier: `ABACUS-` plus one or more dot-separated
/// lowercase alphanumeric segments (`ABACUS-hpg`, `ABACUS-hpg.1`).
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct BeadId(String);

pub const BEAD_ID_PREFIX: &str = "ABACUS-";

impl BeadId {
    pub fn new(raw: &str) -> Result<Self, IdError> {
        if raw.is_empty() {
            return Err(IdError::Empty);
        }
        if raw.len() > MAX_ID_LEN {
            return Err(IdError::TooLong);
        }
        let suffix = raw
            .strip_prefix(BEAD_ID_PREFIX)
            .ok_or(IdError::MissingPrefix)?;
        if suffix.is_empty() {
            return Err(IdError::InvalidStructure);
        }
        for segment in suffix.split('.') {
            if segment.is_empty() {
                return Err(IdError::InvalidStructure);
            }
            if !segment
                .bytes()
                .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit())
            {
                return Err(IdError::InvalidCharacter);
            }
        }
        Ok(Self(raw.to_owned()))
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }

    /// The identifier without its `ABACUS-` prefix.
    pub fn suffix(&self) -> &str {
        &self.0[BEAD_ID_PREFIX.len()..]
    }
}

impl fmt::Display for BeadId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

/// Shared shape rule for opaque generated identifiers: nonempty,
/// bounded, lowercase alphanumeric plus hyphen, starting alphanumeric.
fn validate_opaque(raw: &str) -> Result<(), IdError> {
    if raw.is_empty() {
        return Err(IdError::Empty);
    }
    if raw.len() > MAX_ID_LEN {
        return Err(IdError::TooLong);
    }
    if !raw
        .bytes()
        .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
    {
        return Err(IdError::InvalidCharacter);
    }
    let first = raw.as_bytes()[0];
    if !(first.is_ascii_lowercase() || first.is_ascii_digit()) {
        return Err(IdError::InvalidStructure);
    }
    Ok(())
}

macro_rules! opaque_id {
    ($(#[$doc:meta])* $name:ident) => {
        $(#[$doc])*
        #[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash)]
        pub struct $name(String);

        impl $name {
            pub fn new(raw: &str) -> Result<Self, IdError> {
                validate_opaque(raw)?;
                Ok(Self(raw.to_owned()))
            }

            pub fn as_str(&self) -> &str {
                &self.0
            }
        }

        impl fmt::Display for $name {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                f.write_str(&self.0)
            }
        }
    };
}

